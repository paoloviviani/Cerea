// Bundles the runtime into one ES module that galopin embeds and installs next to a pinned
// playwright-core (the one dependency left external: it ships its own browser driver).
//   npm run bundle        writes ../agent/internal/browserrt/cerea-browser.mjs and package.json
// The bundle starts with the hash of the sources it was made from; a Go test checks it, so a stale
// bundle fails CI instead of shipping.
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { build } from "esbuild";

const root = join(import.meta.dirname, "..");
const target = join(root, "..", "agent", "internal", "browserrt");

export function sourceHash() {
	const files = readdirSync(join(root, "src"))
		.filter((f) => f.endsWith(".ts"))
		.sort();
	const h = createHash("sha256");
	for (const f of files)
		h.update(f)
			.update("\0")
			.update(readFileSync(join(root, "src", f)));
	h.update(readFileSync(join(root, "package.json")));
	return h.digest("hex");
}

const MARK_BEGIN =
	"#### BEGIN browser-runtime (generated by browser-runtime/scripts/bundle.mjs; do not edit)";
const MARK_END = "#### END browser-runtime";

/** The npm packages whose code ended up inside the bundle, from esbuild's metafile. */
function inlinedPackages(metafile) {
	const found = new Map();
	for (const input of Object.keys(metafile.inputs)) {
		const m = /(?:^|\/)node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(input);
		if (!m) continue;
		const dir = input.slice(0, input.indexOf(m[0]) + m[0].length - 1);
		if (found.has(m[1])) continue;
		const meta = JSON.parse(readFileSync(join(root, dir, "package.json"), "utf8"));
		const licenceFile = readdirSync(join(root, dir)).find((f) =>
			/^(licen[cs]e|copying)(\.|$)/i.test(f)
		);
		found.set(m[1], {
			name: m[1],
			version: meta.version,
			licence: typeof meta.license === "string" ? meta.license : (meta.license?.type ?? "see text"),
			text: licenceFile ? readFileSync(join(root, dir, licenceFile), "utf8").trim() : undefined,
			author: typeof meta.author === "string" ? meta.author : meta.author?.name,
		});
	}
	return [...found.values()].sort((a, b) => a.name.localeCompare(b.name));
}

function noticeSection(packages) {
	const rule = "-".repeat(80);
	const parts = [
		MARK_BEGIN,
		"",
		rule,
		"The browser runtime (browser-runtime/, embedded in this binary and installed by",
		"`galopin browser setup`): the npm packages bundled into it",
		rule,
		"",
		"The runtime also installs playwright-core (Apache-2.0) and downloads Playwright's",
		"Chromium into galopin's own directory when `galopin browser setup` runs; both carry",
		"their own licence files there, and are not compiled into this binary.",
		"",
	];
	for (const p of packages) {
		parts.push(
			rule,
			`${p.name} ${p.version}${p.author ? `, ${p.author}` : ""}. Licence: ${p.licence}.`,
			rule,
			""
		);
		parts.push(
			p.text ?? `(No licence file ships with this package; it is licensed ${p.licence}.)`,
			""
		);
	}
	parts.push(MARK_END, "");
	return parts.join("\n");
}

function writeNotices(packages) {
	const file = join(target, "..", "..", "THIRD_PARTY_LICENSES");
	let text = readFileSync(file, "utf8");
	const section = noticeSection(packages);
	const a = text.indexOf(MARK_BEGIN);
	const b = text.indexOf(MARK_END);
	if (a >= 0 && b > a) text = text.slice(0, a) + section + text.slice(b + MARK_END.length + 1);
	else text = `${text.trimEnd()}\n\n${section}`;
	writeFileSync(file, text);
}

const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
mkdirSync(target, { recursive: true });
let packages = [];
const result = await build({
	entryPoints: [join(root, "src", "main.ts")],
	bundle: true,
	platform: "node",
	format: "esm",
	target: "node22",
	external: ["playwright-core"],
	tsconfig: join(root, "tsconfig.json"),
	metafile: true,
	write: false,
	legalComments: "none",
	banner: {
		js: `// cerea-browser runtime ${pkg.version}; source-hash: ${sourceHash()}\nimport { createRequire as __cr } from "node:module";\nconst require = __cr(import.meta.url);`,
	},
});
packages = inlinedPackages(result.metafile);
// The bundle names what it carries, so a test can check each has a notice.
const body = result.outputFiles[0].text;
const firstLine = body.indexOf("\n");
writeFileSync(
	join(target, "cerea-browser.mjs"),
	`${body.slice(0, firstLine)}\n// inlined: ${packages.map((p) => `${p.name}@${p.version}`).join(" ")}${body.slice(firstLine)}`
);
writeNotices(packages);
writeFileSync(
	join(target, "package.json"),
	`${JSON.stringify(
		{
			name: "cerea-browser-runtime-install",
			private: true,
			type: "module",
			description: "Installed by `galopin browser setup`; do not edit.",
			dependencies: { "playwright-core": pkg.dependencies["playwright-core"] },
		},
		null,
		"\t"
	)}\n`
);
console.log(`bundled ${(result.outputFiles[0].text.length / 1024).toFixed(0)} KB`);
