#!/usr/bin/env node
/*
 * Regenerates src/styles/palettes.css — the user-selectable accent and
 * neutral-tone palettes.
 *
 *   node scripts/generate-palettes.mjs && npx prettier --write src/styles/palettes.css
 *
 * Why a generator: Tailwind's colours are oklch, and the contrast test
 * (src/styles/palettes.contrast.test.ts) has to measure exactly what the
 * browser paints. So every shade is written to the CSS as the sRGB hex that
 * Tailwind's own oklch value clips to, and the CSS stays the one source of
 * truth that both the browser and the test read. Edit the tables below, run
 * this, commit the result.
 *
 * Why literal hex rather than `var(--color-teal-600)`: Tailwind 4 only emits
 * a theme variable that some utility actually uses, so `--color-teal-*` does
 * not exist in the bundle (nothing says `bg-teal-600`) and a remap pointing at
 * it would resolve to nothing.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const theme = readFileSync(`${root}node_modules/tailwindcss/theme.css`, "utf8");

const STEPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];

function oklchToHex(css) {
	const m = css.match(/oklch\(\s*([\d.]+)%\s+([\d.]+)\s+([\d.]+)/);
	if (!m) throw new Error(`not an oklch colour: ${css}`);
	const L = parseFloat(m[1]) / 100;
	const a = parseFloat(m[2]) * Math.cos((parseFloat(m[3]) * Math.PI) / 180);
	const b = parseFloat(m[2]) * Math.sin((parseFloat(m[3]) * Math.PI) / 180);
	const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3;
	const mm = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3;
	const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3;
	const lin = [
		4.0767416621 * l - 3.3077115913 * mm + 0.2309699292 * s,
		-1.2684380046 * l + 2.6097574011 * mm - 0.3413193965 * s,
		-0.0041960863 * l - 0.7034186147 * mm + 1.707614701 * s,
	];
	return (
		"#" +
		lin
			.map((v) => {
				v = Math.min(1, Math.max(0, v));
				v = v <= 0.0031308 ? 12.92 * v : 1.055 * v ** (1 / 2.4) - 0.055;
				return Math.round(v * 255)
					.toString(16)
					.padStart(2, "0");
			})
			.join("")
	);
}

function tailwindScale(name) {
	const scale = {};
	for (const step of STEPS) {
		const m = theme.match(new RegExp(`--color-${name}-${step}:\\s*([^;]+);`));
		if (!m) throw new Error(`tailwind has no ${name}-${step}`);
		scale[step] = oklchToHex(m[1]);
	}
	return scale;
}

const mix = (a, b) =>
	"#" +
	[1, 3, 5]
		.map((i) =>
			Math.round((parseInt(a.slice(i, i + 2), 16) + parseInt(b.slice(i, i + 2), 16)) / 2)
				.toString(16)
				.padStart(2, "0")
		)
		.join("");

/*
 * -- accents ----------------------------------------------------------------
 *
 * Each accent *replaces the blue scale*: `bg-blue-600`, `text-blue-400` and
 * the rest keep working untouched and simply paint another hue. A step maps to
 * a step of the same relative luminance, not the same number — Tailwind's
 * teal, green and orange are much lighter than its blue at the same step, so
 * `bg-teal-600` under white text is 3.7:1 where `bg-blue-600` is 5.3:1. The
 * `shifted` table moves the mid steps one darker for those three; violet and
 * rose line up one-for-one. 700 and 800 must stay distinct from 600, because
 * `hover:bg-blue-700` over `bg-blue-600` is the hover state of every primary
 * button.
 */
const identity = Object.fromEntries(STEPS.map((s) => [s, s]));
const shifted = { ...identity, 500: 600, 600: 700, 700: 800, 800: 900, 900: 950 };

const ACCENTS = {
	violet: { from: "violet", steps: identity },
	teal: { from: "teal", steps: shifted },
	green: { from: "green", steps: shifted },
	rose: { from: "rose", steps: identity },
	orange: { from: "orange", steps: shifted },
};

/*
 * -- neutrals ---------------------------------------------------------------
 *
 * The app's gray is its own ramp (main.css), darker at the low end than
 * Tailwind's: its gray-600/700/800/900 sit where Tailwind's slate and stone
 * 700/800/900/950 do. Mapping step-for-step would make every dark surface
 * lighter and bluer than today; mapping by luminance keeps the contrast
 * structure of the default and only adds the tint.
 */
const NEUTRAL_STEPS = { ...identity, 600: 700, 700: 800, 800: 900, 900: 950, 950: 950 };
const NEUTRALS = { slate: "slate", stone: "stone" };

const lines = [];
const out = (s = "") => lines.push(s);

out(`/*
 * User-selectable palettes — GENERATED by scripts/generate-palettes.mjs; edit
 * the tables there, not this file.
 *
 * Cerea-only on purpose: tokens.css is shared byte-for-byte with the console
 * (tokens.drift.test.ts), so nothing here may live in it. The choice is two
 * attributes on <html> — \`data-accent\` and \`data-neutral\` — set on the server
 * from the person's settings so the first paint is already right. The default
 * (blue, gray) is the *absence* of an attribute, so with neither present none
 * of this applies and the look is exactly tokens.css.
 *
 * How it reaches the components without touching them: Tailwind 4 compiles
 * \`bg-blue-600\` to \`background-color: var(--color-blue-600)\`, so remapping the
 * variable repaints every one of the ~290 places that spell a Tailwind blue,
 * and the same for \`gray\`. The semantic tokens (\`--colour-accent*\`, surface,
 * ink, border) are remapped alongside, per theme. The dark rules need the
 * extra \`:root.dark[...]\` specificity to beat tokens.css's own \`.dark\`.
 *
 * Every shade is a literal sRGB hex, so what the contrast test measures is
 * what the browser paints; the comment on each block names the Tailwind step.
 */`);

function accentBlock(name, { from, steps }) {
	const src = tailwindScale(from);
	const at = (step) => src[steps[step]];
	const label = (step) => `${from}-${steps[step]}`;
	out();
	out(
		`/* -- accent: ${name} (blue ${STEPS.map((s) => `${s}→${label(s).split("-")[1]}`).join(" ")}) */`
	);
	out(`:root[data-accent="${name}"] {`);
	for (const step of STEPS) out(`\t--color-blue-${step}: ${at(step)}; /* ${label(step)} */`);
	out(`}`);
	out(`:root[data-accent="${name}"] {`);
	out(`\t--colour-accent: ${at(700)}; /* ${label(700)} */`);
	out(`\t--colour-accent-hover: ${at(800)}; /* ${label(800)} */`);
	out(`\t--colour-accent-subtle: ${at(100)}; /* ${label(100)} */`);
	out(`\t--colour-accent-solid: ${at(600)}; /* ${label(600)} */`);
	out(`\t--colour-accent-solid-hover: ${at(700)}; /* ${label(700)} */`);
	out(`\t--colour-blue: ${at(600)};`);
	out(`}`);
	out(`:root.dark[data-accent="${name}"] {`);
	out(`\t--colour-accent: ${at(400)}; /* ${label(400)} */`);
	out(`\t--colour-accent-hover: ${at(300)}; /* ${label(300)} */`);
	out(`\t--colour-accent-subtle: ${at(950)}; /* ${label(950)} */`);
	out(`\t--colour-accent-solid: ${at(600)}; /* ${label(600)} */`);
	out(`\t--colour-accent-solid-hover: ${at(700)}; /* ${label(700)} */`);
	out(`\t--colour-blue: ${at(400)};`);
	out(`}`);
}

function neutralBlock(name, from) {
	const src = tailwindScale(from);
	const at = (step) => src[NEUTRAL_STEPS[step]];
	const label = (step) => `${from}-${NEUTRAL_STEPS[step]}`;
	out();
	out(
		`/* -- neutral tone: ${name} (gray ${STEPS.map((s) => `${s}→${NEUTRAL_STEPS[s]}`).join(" ")}) */`
	);
	out(`:root[data-neutral="${name}"] {`);
	for (const step of STEPS) out(`\t--color-gray-${step}: ${at(step)}; /* ${label(step)} */`);
	out(`}`);
	out(`:root[data-neutral="${name}"] {`);
	out(`\t--colour-bg: ${at(50)}; /* ${label(50)} */`);
	out(`\t--colour-surface-sunken: ${at(100)}; /* ${label(100)} */`);
	out(`\t--colour-border: ${at(200)}; /* ${label(200)} */`);
	out(`\t--colour-border-strong: ${at(400)}; /* ${label(400)} */`);
	out(`\t--colour-border-quiet: ${at(100)}; /* ${label(100)} */`);
	out(`\t--colour-text: ${at(900)}; /* ${label(900)} */`);
	out(`\t--colour-text-muted: ${at(600)}; /* ${label(600)} */`);
	out(`\t--colour-text-faint: ${at(500)}; /* ${label(500)} */`);
	out(`}`);
	out(`:root.dark[data-neutral="${name}"] {`);
	out(`\t--colour-bg: ${at(900)}; /* ${label(900)} */`);
	out(`\t--colour-surface: ${at(800)}; /* ${label(800)} */`);
	out(`\t--colour-surface-raised: ${at(700)}; /* ${label(700)} */`);
	out(`\t--colour-surface-sunken: ${at(900)}; /* ${label(900)} */`);
	out(`\t--colour-border: ${at(700)}; /* ${label(700)} */`);
	out(`\t--colour-border-strong: ${at(600)}; /* ${label(600)} */`);
	out(
		`\t--colour-border-quiet: ${mix(at(800), at(700))}; /* midway ${label(800)} / ${label(700)} */`
	);
	out(`\t--colour-text: ${at(100)}; /* ${label(100)} */`);
	out(`\t--colour-text-muted: ${at(400)}; /* ${label(400)} */`);
	out(
		`\t--colour-text-faint: ${mix(at(400), at(500))}; /* midway ${label(400)} / ${label(500)} */`
	);
	out(`}`);
}

for (const [name, spec] of Object.entries(ACCENTS)) accentBlock(name, spec);
for (const [name, from] of Object.entries(NEUTRALS)) neutralBlock(name, from);

writeFileSync(`${root}src/styles/palettes.css`, lines.join("\n") + "\n");
console.log(`wrote src/styles/palettes.css (${lines.length} lines)`);
